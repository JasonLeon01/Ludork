std::string MaterialGenerated::resourceDirectory(const std::string& path) {
    if (path.empty()) {
        return "Builtin/Default";
    }
    if (!path.starts_with(materialsPrefix) || !path.ends_with(".json") ||
        path.find_first_of("\\:") != std::string::npos ||
        std::any_of(path.begin(), path.end(), [](unsigned char value) {
            return value < 32;
        })) {
        throw std::invalid_argument(
            "Material path must be Data/Materials/<name>.json: " + path);
    }
    const std::string relative = path.substr(materialsPrefix.size());
    std::size_t begin = 0;
    while (begin <= relative.size()) {
        const std::size_t end = relative.find('/', begin);
        const std::string component = relative.substr(
            begin, end == std::string::npos ? end : end - begin);
        if (component.empty() || component == "." || component == "..") {
            throw std::invalid_argument("Invalid material path: " + path);
        }
        if (end == std::string::npos) {
            break;
        }
        begin = end + 1;
    }
    const std::string stem = relative.substr(0, relative.size() - 5);
    if (stem.empty() || stem.back() == '/') {
        throw std::invalid_argument("Material file name must not be empty: " +
                                    path);
    }
    return "Materials/" + stem;
}

std::string MaterialGenerated::programDirectory(
    const MaterialResource& material, const MaterialResource* layer) {
    layer = effectiveLayer(layer);
    const std::string base = resourceDirectory(material.path());
    if (!layer) {
        return base + "/single";
    }
    const std::string layerDirectory = resourceDirectory(layer->path());
    return base + "/layers/" +
           layerDirectory.substr(std::string_view("Materials/").size());
}

RuntimeData MaterialGenerated::loadMetadata(const std::string& relativePath) {
    constexpr std::string_view extension =
        ludork::generated::resources::DataExtension;
    if (!relativePath.ends_with(extension)) {
        throw std::invalid_argument(
            "Generated material metadata must use a .json path: " +
            relativePath);
    }
    std::string path = std::string(generatedPrefix) + relativePath;
    ludork::runtime::AssetStore& store = ludork::runtime::assetStore();
    const auto status = store.stat(path);
    if (!status || status->directory) {
        const std::string encrypted =
            path.substr(0, path.size() - extension.size()) +
            ludork::generated::resources::EncryptedDataExtension;
        const auto encryptedStatus = store.stat(encrypted);
        if (encryptedStatus && !encryptedStatus->directory) {
            path = encrypted;
        }
    }
    const std::vector<std::uint8_t> contents = store.readAll(path);
    return decodeData(std::string(contents.begin(), contents.end()));
}

RuntimeData MaterialGenerated::compile(const MaterialResource& material,
                                       const MaterialResource* layer) {
    layer = effectiveLayer(layer);
    if (!material.definition() || (layer && !layer->definition())) {
        throw std::invalid_argument(
            "Material Export requires source definitions");
    }
    const std::string directory = programDirectory(material, layer);
    RuntimeData::Map files;
    files.emplace(
        resourceDirectory(material.path()) + "/resource.json",
        RuntimeData(stringifyJSON(resourceMetadata(material)) + '\n'));
    RuntimeData::Map passes;
    RuntimeData analysis;
    for (std::size_t index = 0; index < passNames.size(); ++index) {
        const MaterialCompiler::Sources compiled = MaterialCompiler::compile(
            material, layer, static_cast<MaterialCompiler::Pass>(index));
        if (index == 0) {
            files.emplace(directory + "/vertex.vert",
                          RuntimeData(generatedHeader(material, layer,
                                                      "vertex (shared)") +
                                      compiled.vertex));
            analysis = compiled.analysisProgram->serialize();
        }
        files.emplace(
            directory + "/" + passNames[index] + ".frag",
            RuntimeData(generatedHeader(material, layer, passNames[index]) +
                        compiled.fragment));
        passes.emplace(passNames[index], uniformMetadata(compiled.uniforms));
    }
    const RuntimeData metadata(RuntimeData::Map{
        {"type", RuntimeData("materialProgram")},
        {"version", RuntimeData(std::int64_t{1})},
        {"generator", RuntimeData(generator)},
        {"material", RuntimeData(material.path())},
        {"signature", RuntimeData(material.signature())},
        {"layer", RuntimeData(layer ? layer->path() : "")},
        {"layerSignature", RuntimeData(layer ? layer->signature() : "")},
        {"passes", RuntimeData(std::move(passes))},
        {"analysis", std::move(analysis)}});
    files.emplace(directory + "/program.json",
                  RuntimeData(stringifyJSON(metadata) + '\n'));
    return RuntimeData(
        RuntimeData::Map{{"files", RuntimeData(std::move(files))}});
}

MaterialCompiler::Sources MaterialGenerated::sources(
    const MaterialResource& material, const MaterialResource* layer,
    MaterialCompiler::Pass pass) {
    layer = effectiveLayer(layer);
    const std::size_t index = passIndex(pass);
    const auto generated = program(material, layer);
    if (generated->previewSources) {
        return (*generated->previewSources)[index];
    }
    const std::string directory =
        std::string(generatedPrefix) + programDirectory(material, layer);
    MaterialCompiler::Sources result;
    result.vertex = shaderSource(directory + "/vertex.vert");
    result.fragment =
        shaderSource(directory + "/" + passNames[index] + ".frag");
    result.uniforms = generated->uniforms[index];
    result.analysisProgram = generated->analysisProgram;
    result.analysis = result.analysisProgram->evaluate(
        material.resolveParameters({}),
        layer ? layer->resolveParameters({}) : RuntimeData::Map{});
    return result;
}

std::shared_ptr<const MaterialAnalysisProgram>
MaterialGenerated::analysisProgram(const MaterialResource& material,
                                   const MaterialResource* layer) {
    return program(material, effectiveLayer(layer))->analysisProgram;
}

void MaterialGenerated::clearCache() {
    programCache(false).clear();
    programCache(true).clear();
}

