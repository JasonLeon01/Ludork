constexpr std::string_view materialsPrefix = "Data/Materials/";
constexpr std::string_view generatedPrefix =
    "/Game/Assets/Shaders/MaterialGenerated/";
constexpr std::array<const char*, 4> passNames{"color", "surface",
                                               "transmission", "source"};
constexpr const char* generator = "Ludork Material Export";
constexpr const char* shaderHeader =
    "// Automatically generated by Ludork Material Export. Do not edit.\n";

ludork::runtime::ConcurrentResourceCache<const MaterialGeneratedProgramImpl,
                                         true>&
programCache(bool preview) {
    static ludork::runtime::ConcurrentResourceCache<
        const MaterialGeneratedProgramImpl, true>
        cache;
    static ludork::runtime::ConcurrentResourceCache<
        const MaterialGeneratedProgramImpl, true>
        previewCache;
    return preview ? previewCache : cache;
}

const MaterialResource* effectiveLayer(const MaterialResource* layer) {
    return layer && !layer->path().empty() ? layer : nullptr;
}

const RuntimeData& required(const RuntimeData::Map& fields,
                            const std::string& name) {
    return ludork::runtime::value_reader::requireValue(
        fields, name, "generated material program");
}

std::string text(const RuntimeData::Map& fields, const std::string& name) {
    return ludork::runtime::value_reader::requireString(
        required(fields, name), "generated material program." + name);
}

std::size_t passIndex(MaterialCompiler::Pass pass) {
    const auto index = static_cast<std::size_t>(pass);
    if (index >= passNames.size()) {
        throw std::invalid_argument("Unknown material pass");
    }
    return index;
}

std::string programKey(const MaterialResource& material,
                       const MaterialResource* layer) {
    return MaterialGenerated::programDirectory(material, layer) + '\0' +
           material.signature() + '\0' + (layer ? layer->signature() : "") +
           '\0' + (material.definition() ? "preview" : "runtime");
}

std::vector<MaterialCompiler::Uniform> readUniforms(
    const RuntimeData& value, const MaterialResource& material,
    const MaterialResource* layer) {
    std::vector<MaterialCompiler::Uniform> result;
    std::unordered_set<std::string> names;
    for (const RuntimeData& entry : ludork::runtime::value_reader::requireArray(
             value, "material uniforms")) {
        const auto& fields = ludork::runtime::value_reader::requireMap(
            entry, "material uniform");
        MaterialCompiler::Uniform uniform{
            text(fields, "name"), text(fields, "parameter"),
            text(fields, "type"),
            ludork::runtime::value_reader::requireBool(
                required(fields, "layer"), "material uniform.layer")};
        const MaterialResource* resource = uniform.layer ? layer : &material;
        if (!resource || uniform.name.empty() ||
            !names.insert(uniform.name).second) {
            throw std::invalid_argument("Invalid generated material uniform: " +
                                        uniform.name);
        }
        const auto parameter = std::find_if(
            resource->parameters().begin(), resource->parameters().end(),
            [&uniform](const MaterialResource::Parameter& item) {
                return item.id == uniform.parameter;
            });
        if (parameter == resource->parameters().end() ||
            parameter->type != uniform.type) {
            throw std::invalid_argument(
                "Generated material uniform does not match its parameter: " +
                uniform.parameter);
        }
        result.push_back(std::move(uniform));
    }
    return result;
}

std::shared_ptr<const MaterialGeneratedProgramImpl> program(
    const MaterialResource& material, const MaterialResource* layer) {
    auto& cache = programCache(material.definition() != nullptr);
    if (material.definition() && cache.entryCount() >= 256) {
        cache.clear();
    }
    return cache.getOrLoad(programKey(material, layer), [&material, layer]() {
        auto result = std::make_shared<MaterialGeneratedProgramImpl>();
        if (material.definition()) {
            if (layer && !layer->definition()) {
                throw std::invalid_argument(
                    "Editor material preview requires layer definitions");
            }
            result->previewSources.emplace();
            for (std::size_t index = 0; index < passNames.size(); ++index) {
                (*result->previewSources)[index] = MaterialCompiler::compile(
                    material, layer,
                    static_cast<MaterialCompiler::Pass>(index));
            }
            result->analysisProgram =
                (*result->previewSources)[0].analysisProgram;
            return result;
        }
        if (layer && layer->definition()) {
            throw std::invalid_argument(
                "Runtime materials cannot use editor layer definitions");
        }
        const std::string path =
            MaterialGenerated::programDirectory(material, layer) +
            "/program.json";
        const RuntimeData data = MaterialGenerated::loadMetadata(path);
        const RuntimeData::Map& fields =
            ludork::runtime::value_reader::requireMap(
                data, "generated material program");
        if (text(fields, "type") != "materialProgram" ||
            ludork::runtime::value_reader::requireInt(
                required(fields, "version"), "material program.version") != 1 ||
            text(fields, "generator") != generator ||
            text(fields, "material") != material.path() ||
            text(fields, "signature") != material.signature() ||
            text(fields, "layer") != (layer ? layer->path() : "") ||
            text(fields, "layerSignature") !=
                (layer ? layer->signature() : "")) {
            throw std::invalid_argument(
                "Generated material program is invalid or stale: " + path);
        }
        const auto& passes = ludork::runtime::value_reader::requireMap(
            required(fields, "passes"), "material program.passes");
        for (std::size_t index = 0; index < passNames.size(); ++index) {
            result->uniforms[index] = readUniforms(
                required(passes, passNames[index]), material, layer);
        }
        result->analysisProgram =
            MaterialAnalysisProgram::deserialize(required(fields, "analysis"));
        return result;
    });
}

RuntimeData resourceMetadata(const MaterialResource& material) {
    RuntimeData::Array parameters;
    for (const MaterialResource::Parameter& parameter : material.parameters()) {
        RuntimeData::Map fields{
            {"id", RuntimeData(parameter.id)},
            {"displayName", RuntimeData(parameter.displayName)},
            {"type", RuntimeData(parameter.type)},
            {"default", parameter.defaultValue},
            {"group", RuntimeData(parameter.group)}};
        if (parameter.minimum) {
            fields.emplace(
                "min", RuntimeData(static_cast<double>(*parameter.minimum)));
        }
        if (parameter.maximum) {
            fields.emplace(
                "max", RuntimeData(static_cast<double>(*parameter.maximum)));
        }
        parameters.emplace_back(std::move(fields));
    }
    const sf::Vector2f maximum = material.maximumVertexOffset();
    return RuntimeData(RuntimeData::Map{
        {"type", RuntimeData("materialResource")},
        {"version", RuntimeData(std::int64_t{1})},
        {"generator", RuntimeData(generator)},
        {"material", RuntimeData(material.path())},
        {"signature", RuntimeData(material.signature())},
        {"parameters", RuntimeData(std::move(parameters))},
        {"rendering",
         RuntimeData(RuntimeData::Map{
             {"maxVertexOffset",
              RuntimeData(RuntimeData::Array{
                  RuntimeData(static_cast<double>(maximum.x)),
                  RuntimeData(static_cast<double>(maximum.y))})}})}});
}

RuntimeData uniformMetadata(
    const std::vector<MaterialCompiler::Uniform>& uniforms) {
    RuntimeData::Array result;
    for (const MaterialCompiler::Uniform& uniform : uniforms) {
        result.emplace_back(
            RuntimeData::Map{{"name", RuntimeData(uniform.name)},
                             {"parameter", RuntimeData(uniform.parameter)},
                             {"type", RuntimeData(uniform.type)},
                             {"layer", RuntimeData(uniform.layer)}});
    }
    return RuntimeData(std::move(result));
}

std::string shaderSource(const std::string& path) {
    ShaderLoader::ShaderSourceResult source = ShaderLoader::readSource(path);
    if (!source) {
        throw std::runtime_error("Could not read generated material shader: " +
                                 path + "\n" + source.error);
    }
    return std::move(source.source);
}

std::string generatedHeader(const MaterialResource& material,
                            const MaterialResource* layer,
                            const std::string& pass) {
    return std::string(shaderHeader) + "// Material: " +
           (material.path().empty() ? "<builtin default>" : material.path()) +
           "\n// Layer: " + (layer ? layer->path() : "<none>") +
           "\n// Pass: " + pass + '\n';
}

