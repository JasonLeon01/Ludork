using Ludork.Models;
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Threading;
using System.Threading.Tasks;

namespace Ludork.Services;

public sealed class MaterialGenerationService : IAsyncDisposable
{
    private const string GeneratedRoot = "Assets/Shaders/MaterialGenerated/";
    private const string RecordPath = GeneratedRoot + "export.json";
    private const string Generator = "Ludork Material Export";
    private const string ShaderMarker = "// Automatically generated by Ludork Material Export. Do not edit.";
    private static readonly UTF8Encoding utf8 = new(false, true);
    private static readonly JsonSerializerOptions jsonOptions = new() { WriteIndented = true, NewLine = "\n" };
    private readonly string projectPath;
    private readonly PreviewRuntimeService runtime;
    private readonly PreviewHostConnection connection;
    private string? buildId;

    public MaterialGenerationService(string projectPath)
    {
        this.projectPath = Path.GetFullPath(projectPath);
        runtime = new PreviewRuntimeService(this.projectPath);
        connection = new PreviewHostConnection(runtime);
    }

    public async Task PrepareAsync(CancellationToken cancellationToken)
    {
        if (!await connection.StartAsync(cancellationToken))
            throw new InvalidOperationException(connection.StatusMessage);
        if (!connection.Capabilities.Contains("materialExport"))
            throw new InvalidOperationException("The preview runtime does not support material export. Rebuild the project runtime.");
        buildId = runtime.Current!.BuildId;
    }

    public async Task<SaveResult> GenerateAsync(JsonElement manifest, Action<string> writeOutput, CancellationToken cancellationToken)
    {
        string staging = Path.Combine(Path.GetTempPath(), "LudorkMaterials-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(staging);
        try
        {
            return await generateAsync(manifest, staging, writeOutput, cancellationToken);
        }
        finally
        {
            Directory.Delete(staging, true);
        }
    }

    private async Task<SaveResult> generateAsync(JsonElement manifest, string staging, Action<string> writeOutput, CancellationToken cancellationToken)
    {
        Dictionary<string, JsonObject> materials = new(StringComparer.Ordinal);
        foreach (JsonElement entry in manifest.GetProperty("materialPaths").EnumerateArray())
        {
            string path = entry.GetString() ?? throw new InvalidDataException("Invalid material input path.");
            if (!GameDataPath.TryGetMaterialKey(path, out _))
                throw new InvalidDataException("Invalid material input path: " + path);
            materials.Add(path, JsonNode.Parse(await File.ReadAllTextAsync(resolve(path), cancellationToken)) as JsonObject
                ?? throw new InvalidDataException("Material must be an object: " + path));
        }
        JsonElement[] programs = manifest.GetProperty("programs").EnumerateArray().ToArray();
        SortedDictionary<string, GeneratedFile> outputs = new(StringComparer.Ordinal);
        int completed = 0;
        foreach (JsonElement program in programs)
        {
            string materialPath = program.GetProperty("material").GetString()
                ?? throw new InvalidDataException("Invalid material program path.");
            string layerPath = program.GetProperty("layer").GetString()
                ?? throw new InvalidDataException("Invalid layer program path.");
            cancellationToken.ThrowIfCancellationRequested();
            JsonObject response = await connection.ExchangeAsync(new JsonObject
            {
                ["type"] = "compileMaterial",
                ["materialPath"] = materialPath,
                ["asset"] = materialPath.Length == 0 ? null : materials[materialPath].DeepClone(),
                ["layerPath"] = layerPath,
                ["layerAsset"] = layerPath.Length == 0 ? null : materials[layerPath].DeepClone(),
            }, cancellationToken);
            if (response["type"]?.GetValue<string>() != "compiledMaterial" || response["files"] is not JsonObject files)
                throw new InvalidDataException(response["message"]?.GetValue<string>() ?? "Material export returned an invalid response.");
            foreach (KeyValuePair<string, JsonNode?> file in files)
            {
                string path = GeneratedRoot + file.Key;
                resolve(path);
                if (path == RecordPath)
                    throw new InvalidDataException("Material compiler returned a reserved output path.");
                byte[] content = utf8.GetBytes(file.Value?.GetValue<string>()
                    ?? throw new InvalidDataException("Material compiler returned an invalid file: " + path));
                if (!isGenerated(path, content))
                    throw new InvalidDataException("Material compiler omitted the generated marker: " + path);
                if (path.EndsWith(".json", StringComparison.Ordinal))
                    content = canonicalizeJson(content);
                string hash = Convert.ToHexStringLower(SHA256.HashData(content));
                if (outputs.TryGetValue(path, out GeneratedFile? previous))
                {
                    if (previous.Hash != hash)
                        throw new InvalidDataException("Material compiler returned conflicting output: " + path);
                    continue;
                }
                string temporary = Path.Combine(staging, outputs.Count.ToString(System.Globalization.CultureInfo.InvariantCulture));
                await File.WriteAllBytesAsync(temporary, content, cancellationToken);
                outputs.Add(path, new GeneratedFile(temporary, hash));
            }
            completed++;
            writeOutput($"Material export: {completed}/{programs.Length} ({(materialPath.Length == 0 ? "built-in default" : materialPath)})");
        }
        HashSet<string> expected = manifest.GetProperty("expectedOutputPaths").EnumerateArray()
            .Select(entry => entry.GetString() ?? throw new InvalidDataException("Invalid material output path."))
            .Where(path => path != RecordPath).ToHashSet(StringComparer.Ordinal);
        if (!expected.SetEquals(outputs.Keys))
            throw new InvalidDataException("Material compiler outputs do not match the export manifest.");
        JsonObject inputs = new();
        foreach (JsonProperty input in manifest.GetProperty("inputs").EnumerateObject().OrderBy(value => value.Name, StringComparer.Ordinal))
        {
            if (input.Name != "EditorCache/Preview.json")
                inputs[input.Name] = input.Value.GetString();
        }
        JsonObject hashes = new();
        foreach (KeyValuePair<string, GeneratedFile> output in outputs)
            hashes[output.Key] = output.Value.Hash;
        byte[] record = utf8.GetBytes(new JsonObject
        {
            ["formatVersion"] = 1,
            ["generator"] = Generator,
            ["inputs"] = inputs,
            ["outputs"] = hashes,
        }.ToJsonString(jsonOptions) + "\n");
        string recordFile = Path.Combine(staging, "export.json");
        await File.WriteAllBytesAsync(recordFile, record, cancellationToken);
        outputs[RecordPath] = new GeneratedFile(recordFile, Convert.ToHexStringLower(SHA256.HashData(record)));
        await runtime.RefreshAsync(cancellationToken);
        if (!runtime.IsReady || runtime.Current?.BuildId != buildId)
            throw new InvalidDataException("Material compiler changed during export. Export the project again.");
        return await Task.Run(() => install(manifest, outputs, cancellationToken), cancellationToken);
    }

    private SaveResult install(JsonElement manifest, SortedDictionary<string, GeneratedFile> outputs, CancellationToken cancellationToken)
    {
        foreach (JsonProperty input in manifest.GetProperty("inputs").EnumerateObject())
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (hashInput(input.Name) != input.Value.GetString())
                throw new InvalidDataException("Material export inputs changed: " + input.Name);
        }
        EditorFileSaveBatch batch = new();
        HashSet<string> owned = readOwnedOutputs();
        foreach (KeyValuePair<string, GeneratedFile> output in outputs)
        {
            cancellationToken.ThrowIfCancellationRequested();
            string path = resolve(output.Key);
            string generatedDirectory = resolve(GeneratedRoot.TrimEnd('/'));
            for (string? parent = Path.GetDirectoryName(path); parent is not null && parent.Length >= generatedDirectory.Length;
                parent = Path.GetDirectoryName(parent))
                batch.EnsureDirectoryCase(parent);
            if (Directory.Exists(path))
                throw new InvalidDataException("Material output is occupied by a directory: " + output.Key);
            if (File.Exists(path))
            {
                byte[] existing = File.ReadAllBytes(path);
                if (!owned.Contains(output.Key) && !isGenerated(output.Key, existing))
                    throw new InvalidDataException("Material output conflicts with handwritten content: " + output.Key);
                if (Convert.ToHexStringLower(SHA256.HashData(existing)) == output.Value.Hash)
                    continue;
            }
            batch.WriteFromFile(path, output.Value.Path);
        }
        foreach (JsonElement entry in manifest.GetProperty("outputPaths").EnumerateArray())
        {
            cancellationToken.ThrowIfCancellationRequested();
            string relative = entry.GetString() ?? throw new InvalidDataException("Invalid material output path.");
            if (!relative.StartsWith(GeneratedRoot, StringComparison.Ordinal))
                throw new InvalidDataException("Material output is outside the generated directory: " + relative);
            string path = resolve(relative);
            if (outputs.ContainsKey(relative) || !File.Exists(path))
                continue;
            if (!owned.Contains(relative) && !isGenerated(relative, File.ReadAllBytes(path)))
                throw new InvalidDataException("Unexpected handwritten file in the material export directory: " + relative);
            batch.Delete(path);
        }
        cancellationToken.ThrowIfCancellationRequested();
        return batch.Execute(cancellationToken: cancellationToken);
    }

    private string hashInput(string relative)
    {
        string path = resolve(relative);
        if (!File.Exists(path))
            return "missing";
        byte[] content = File.ReadAllBytes(path);
        int length = content.Length;
        if (relative != "EditorCache/Preview.json")
        {
            length = 0;
            for (int index = 0; index < content.Length; index++)
            {
                if (content[index] == '\r' && index + 1 < content.Length && content[index + 1] == '\n')
                    continue;
                content[length++] = content[index];
            }
        }
        return Convert.ToHexStringLower(SHA256.HashData(content.AsSpan(0, length)));
    }

    private HashSet<string> readOwnedOutputs()
    {
        string path = resolve(RecordPath);
        if (!File.Exists(path))
            return new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        JsonObject record = JsonNode.Parse(File.ReadAllBytes(path)) as JsonObject
            ?? throw new InvalidDataException("Invalid material export record. Remove Assets/Shaders/MaterialGenerated and export again.");
        if (record["generator"]?.GetValue<string>() != Generator || record["outputs"] is not JsonObject outputs)
            throw new InvalidDataException("Material export record has no generated-file ownership information.");
        HashSet<string> owned = outputs.Select(entry => entry.Key).ToHashSet(StringComparer.OrdinalIgnoreCase);
        if (owned.Any(relative => !relative.StartsWith(GeneratedRoot, StringComparison.Ordinal)))
            throw new InvalidDataException("Material export record contains an invalid output path.");
        owned.Add(RecordPath);
        return owned;
    }

    private static byte[] canonicalizeJson(byte[] data)
    {
        using JsonDocument document = JsonDocument.Parse(data);
        using MemoryStream output = new();
        using (Utf8JsonWriter writer = new(output))
            writeCanonicalJson(writer, document.RootElement);
        output.WriteByte((byte)'\n');
        return output.ToArray();
    }

    private static void writeCanonicalJson(Utf8JsonWriter writer, JsonElement value)
    {
        if (value.ValueKind == JsonValueKind.Object)
        {
            writer.WriteStartObject();
            foreach (JsonProperty property in value.EnumerateObject().OrderBy(property => property.Name, StringComparer.Ordinal))
            {
                writer.WritePropertyName(property.Name);
                writeCanonicalJson(writer, property.Value);
            }
            writer.WriteEndObject();
        }
        else if (value.ValueKind == JsonValueKind.Array)
        {
            writer.WriteStartArray();
            foreach (JsonElement item in value.EnumerateArray())
                writeCanonicalJson(writer, item);
            writer.WriteEndArray();
        }
        else
            value.WriteTo(writer);
    }

    private static bool isGenerated(string path, byte[] data)
    {
        string content = utf8.GetString(data);
        if (path.EndsWith(".vert", StringComparison.Ordinal) || path.EndsWith(".frag", StringComparison.Ordinal))
            return content.StartsWith(ShaderMarker, StringComparison.Ordinal);
        if (!path.EndsWith(".json", StringComparison.Ordinal))
            return false;
        return JsonNode.Parse(content) is JsonObject value && value["generator"]?.GetValue<string>() == Generator;
    }

    private string resolve(string relative)
    {
        string[] parts = relative.Split('/');
        if (Path.IsPathRooted(relative) || relative.Contains('\\') || relative.Contains(':')
            || parts.Any(part => part.Length == 0 || part is "." or ".."))
            throw new InvalidDataException("Invalid material export path: " + relative);
        string path = projectPath;
        foreach (string part in parts)
        {
            path = Path.Combine(path, part);
            if (EditorPathSandbox.IsLink(path))
                throw new InvalidDataException("Material export paths must not contain symbolic links: " + relative);
        }
        return path;
    }

    public async ValueTask DisposeAsync()
    {
        await connection.DisposeAsync();
        await runtime.DisposeAsync();
    }

    private sealed record GeneratedFile(string Path, string Hash);
}
